import {canonicalRedirect} from './canonical-redirects.js';
import express from 'express';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import cookieParser from 'cookie-parser';
import db from './db.js';
import {ensureAdminUser,syncAdminFromEnv} from './auth.js';
import {websiteSchema} from './website-schema.js';
import {initWebsite} from './init-website.js';
import {getWebsite} from './website.js';
import apiRouter from './routes.js';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const app=express();
app.set('trust proxy',1);app.disable('x-powered-by');
app.use(express.json({limit:'2mb'}));app.use(cookieParser());
websiteSchema();initWebsite();ensureAdminUser();syncAdminFromEnv();
app.use('/api',apiRouter);
app.use('/admin',(req,res,next)=>{res.set('Cache-Control','no-store');res.set('X-Robots-Tag','noindex, nofollow');next();},express.static(path.join(ROOT,'admin')));
app.use('/uploads',express.static(path.join(process.env.DATA_DIR||path.join(ROOT,'data'),'uploads')));
app.get('/health',(_req,res)=>res.json({ok:true}));
const sendWebsite=(req,res)=>{
 const website=getWebsite();
 const bootstrap=JSON.stringify(website).replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/&/g,'\\u0026').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
 const escape=value=>String(value).replace(/[&<>"]/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[char]));
 let title={'/':'Strona główna','/zespol':'Zespół','/partnerzy':'Partnerzy','/kontakt':'Kontakt','/aktualnosci':'Aktualności','/projekty':'Projekty'}[req.path];
 if(req.params.projectId)title=website.P[req.params.projectId]?.name;
 if(req.params.articleId)title=website.POSTS.find(post=>post.id===req.params.articleId)?.t;
 const page=fs.readFileSync(path.join(ROOT,'index.html'),'utf8').replace('__WEBSITE_BOOTSTRAP__',()=>bootstrap).replace('<title>Strona główna | KN SPA</title>','<title>'+escape(title||'Strona główna')+' | KN SPA</title>').replace('href="https://knspa.mimuw.edu.pl/"','href="https://knspa.mimuw.edu.pl'+escape(req.path)+'"');
 res.set('Cache-Control','no-store');res.type('html').send(page);
};
const notFound=res=>res.status(404).sendFile(path.join(ROOT,'404.html'));
app.use(canonicalRedirect);
app.get(['/','/kontakt','/zespol','/partnerzy','/projekty','/aktualnosci'],sendWebsite);
app.get('/projekty/:projectId',(req,res)=>db.prepare('SELECT id FROM projects WHERE id=?').get(req.params.projectId)?sendWebsite(req,res):notFound(res));
app.get('/aktualnosci/:articleId',(req,res)=>db.prepare('SELECT id FROM news WHERE id=? AND published=1').get(req.params.articleId)?sendWebsite(req,res):notFound(res));
app.get(['/test','/test/','/test/index.html'],(_req,res)=>res.redirect(302,'/'));
const redirects={'/index.html':'/','/projects':'/projekty','/projects.html':'/projekty','/team':'/zespol','/team.html':'/zespol','/contact':'/kontakt','/contact.html':'/kontakt','/bluespark':'/projekty/bluespark','/bluespark/':'/projekty/bluespark'};
for(const [route,target] of Object.entries(redirects))app.get(route,(_req,res)=>res.redirect(301,target));
for(const entity of [{path:'/news/:id',file:'/article.html',query:'id',table:'news',base:'/aktualnosci/',condition:' AND published=1'},{path:'/project/:id',file:'/project.html',query:'id',table:'projects',base:'/projekty/',condition:''},{path:'/member/:id',file:'/member.html',query:'user',table:'members',base:'/zespol',condition:' AND is_active=1'}]){
 const handler=(req,res)=>{
  const id=req.params.id??req.query[entity.query];
  if(typeof id!=='string'||!db.prepare('SELECT id FROM '+entity.table+' WHERE id=?'+entity.condition).get(id))return notFound(res);
  res.redirect(301,entity.base+(entity.table==='members'?'':encodeURIComponent(id)));
 };
 app.get(entity.path,handler);app.get(entity.file,handler);
}
app.get('/robots.txt',(_req,res)=>res.type('text/plain').send('User-agent: *\nDisallow: /admin/\nDisallow: /api/\n'));
app.use((_req,res)=>res.status(404).sendFile(path.join(ROOT,'404.html')));
app.listen(Number(process.env.PORT)||3000,'127.0.0.1',()=>console.log('KN SPA redesigned website ready'));
